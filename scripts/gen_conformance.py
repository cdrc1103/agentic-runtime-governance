"""Generate ``docs/conformance.md``: requirement -> abstract class -> tests, and scenarios.

Inputs: ``docs/spec/requirements.md``, ``docs/spec/reference-principles.md`` (extension point
table), ``conformance/scenarios.md``, and the files written by ``pytest --req-report``
(``conformance/matrix.yaml``, ``conformance/scenario-results.yaml``).
``--check`` exits non-zero if the committed document is stale.
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).parent.parent
OUT = ROOT / "docs" / "conformance.md"
REQ_ROW = re.compile(r"^\| ([A-Z]+-\d+) \| (PAPER|DESIGN) \| (.+?) \| (.+?) \|$", re.M)
EXT_ROW = re.compile(r"^\| `(\w+)` \| .+? \| .+? \| (.+?) \|$", re.M)
SCN_ROW = re.compile(r"^\| (S\d+) \| (.+?) \| (.+?) \| (.+?) \|$", re.M)


def expand(token: str, known: list[str]) -> list[str]:
    """Expand ``IDN-01/03/04``, ``AUD-01..06`` and bare prefixes like ``ESC`` to IDs."""
    token = token.strip()
    m = re.fullmatch(r"([A-Z]+)-(\d+)\.\.(\d+)", token)
    if m:
        lo, hi = int(m.group(2)), int(m.group(3))
        return [f"{m.group(1)}-{n:02d}" for n in range(lo, hi + 1)]
    m = re.fullmatch(r"([A-Z]+)-(\d+(?:/\d+)*)", token)
    if m:
        return [f"{m.group(1)}-{n}" for n in m.group(2).split("/")]
    if re.fullmatch(r"[A-Z]+", token):
        return [k for k in known if k.startswith(token + "-")]
    return []


def render() -> str:
    """Build the document text."""
    reqs = {m[0]: m[1:] for m in REQ_ROW.findall((ROOT / "docs/spec/requirements.md").read_text())}
    ids = list(reqs)
    classes: dict[str, list[str]] = {}
    principles = (ROOT / "docs/spec/reference-principles.md").read_text()
    for cls, ref in EXT_ROW.findall(principles):
        for tok in ref.split(","):
            for rid in expand(tok, ids):
                classes.setdefault(rid, []).append(cls)
    matrix = yaml.safe_load((ROOT / "conformance/matrix.yaml").read_text()) or {}
    results = yaml.safe_load((ROOT / "conformance/scenario-results.yaml").read_text()) or {}
    lines = [
        "# Conformance matrix",
        "",
        "> Generated by `scripts/gen_conformance.py` from the `@pytest.mark.req` / `scenario` "
        "markers. Unofficial reference implementation based on the SAFR white paper; this is "
        "traceability, **not** a certification or a statement of compliance with anything.",
        "",
        "## Requirements",
        "",
        "| ID | Tag | Requirement (short) | Abstract class(es) | Tests |",
        "|---|---|---|---|---|",
    ]
    for rid, (tag, text, _) in reqs.items():
        short = text.split(". ")[0].replace("|", "/")[:110]
        n = len(matrix.get(rid, []))
        lines.append(
            f"| {rid} | {tag} | {short} | {', '.join(f'`{c}`' for c in classes.get(rid, [])) or '-'}"
            f" | {n or 'none'} |"
        )
    paper = [r for r, v in reqs.items() if v[0] == "PAPER"]
    covered = [r for r in paper if matrix.get(r)]
    lines += ["", f"[PAPER] requirements with at least one test: {len(covered)}/{len(paper)}.", ""]
    lines += ["## Scenarios", "", "| ID | Scenario | Proves | Tests |", "|---|---|---|---|"]
    scenarios = SCN_ROW.findall((ROOT / "conformance/scenarios.md").read_text())
    for sid, name, _expected, proves in scenarios:
        tests = results.get(sid, [])
        short = ", ".join(sorted({t.split("::")[-1].split("[")[0] for t in tests}))
        patterns = sorted({t.split("[")[1].rstrip("]") for t in tests if "[" in t})
        suffix = f" ({'/'.join(patterns)})" if patterns else ""
        lines.append(f"| {sid} | {name} | {proves} | `{short or 'none'}`{suffix} |")
    done = sum(1 for sid, *_ in scenarios if results.get(sid))
    lines += ["", f"Scenarios with a test: {done}/{len(scenarios)}.", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Write the document, or with ``--check`` verify it is current."""
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/conformance.md is stale; run scripts/gen_conformance.py")
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
